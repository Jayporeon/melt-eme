// Font subsetting. The video only ever draws its own lyrics, translation and credits, so each font is cut down to
// exactly those characters: the web page then loads 13 small font files instead of hundreds of unicode-range
// slices. Output (committed): src/fonts/*.woff2, src/fonts/fonts.css (imported by main.ts) and src/fonts/chars.txt.
//
//   bun scripts/fonts.ts           regenerate. Downloads the full fonts from github.com/google/fonts once, into .fontcache/
//   bun scripts/fonts.ts --check   fail if the lyrics or the code use a character the fonts do not cover (runs before every build)
//
// Run it after editing lyrics.txt / the translation (after build_data.py) or any text written in src/.
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const ROOT = resolve(import.meta.dir, '..');
const OUT = join(ROOT, 'src/fonts');
const CACHE = join(ROOT, '.fontcache');
const GF = 'https://raw.githubusercontent.com/google/fonts/main/ofl/';

// family name as used in src/engine/type.ts (F), weight (or variable range), file in google/fonts
const FONTS: { family: string; weight: string; src: string }[] = [
  { family: 'Dela Gothic One', weight: '400', src: 'delagothicone/DelaGothicOne-Regular.ttf' },
  { family: 'Hachi Maru Pop', weight: '400', src: 'hachimarupop/HachiMaruPop-Regular.ttf' },
  { family: 'M PLUS 1 Variable', weight: '100 900', src: 'mplus1/MPLUS1[wght].ttf' },
  { family: 'DotGothic16', weight: '400', src: 'dotgothic16/DotGothic16-Regular.ttf' },
  { family: 'Klee One', weight: '400', src: 'kleeone/KleeOne-Regular.ttf' },
  { family: 'Klee One', weight: '600', src: 'kleeone/KleeOne-SemiBold.ttf' },
  { family: 'Shippori Mincho B1', weight: '500', src: 'shipporiminchob1/ShipporiMinchoB1-Medium.ttf' },
  { family: 'Shippori Mincho B1', weight: '800', src: 'shipporiminchob1/ShipporiMinchoB1-ExtraBold.ttf' },
  { family: 'IBM Plex Mono', weight: '400', src: 'ibmplexmono/IBMPlexMono-Regular.ttf' },
  { family: 'IBM Plex Mono', weight: '500', src: 'ibmplexmono/IBMPlexMono-Medium.ttf' },
  { family: 'Zen Maru Gothic', weight: '500', src: 'zenmarugothic/ZenMaruGothic-Medium.ttf' },
  { family: 'Zen Maru Gothic', weight: '900', src: 'zenmarugothic/ZenMaruGothic-Black.ttf' },
];

/** every character the video can draw: all strings in lyrics.json, every character in src/ (string literals such as
 *  the credits and EXTRA_TEXT; comments only add a few spare glyphs) and printable ASCII */
function usedChars(): string[] {
  const set = new Set<string>();
  const addText = (s: string) => {
    for (const c of s) if (c >= ' ') set.add(c);
  };
  const walk = (v: unknown) => {
    if (typeof v === 'string') addText(v);
    else if (v && typeof v === 'object') for (const x of Object.values(v)) walk(x);
  };
  walk(JSON.parse(readFileSync(join(ROOT, 'public/data/lyrics.json'), 'utf8')));
  const scan = (dir: string) => {
    for (const n of readdirSync(dir)) {
      const p = join(dir, n);
      if (statSync(p).isDirectory()) {
        if (p !== OUT) scan(p);
      } else if (n.endsWith('.ts')) addText(readFileSync(p, 'utf8'));
    }
  };
  scan(join(ROOT, 'src'));
  for (let i = 0x20; i < 0x7f; i++) set.add(String.fromCharCode(i));
  return [...set].sort();
}

const chars = usedChars();
const charsFile = join(OUT, 'chars.txt');

if (process.argv.includes('--check')) {
  const have = new Set(existsSync(charsFile) ? [...readFileSync(charsFile, 'utf8')] : []);
  const missing = chars.filter((c) => !have.has(c));
  if (missing.length) {
    console.error(`fonts: ${missing.length} character(s) not in the subset fonts: ${missing.join('')}\nrun: bun scripts/fonts.ts`);
    process.exit(1);
  }
  process.exit(0);
}

const { default: subsetFont } = await import('subset-font');
mkdirSync(CACHE, { recursive: true });
mkdirSync(OUT, { recursive: true });
const text = chars.join('');
const css: string[] = [
  '/* generated by scripts/fonts.ts: fonts subset to src/fonts/chars.txt. Fonts: SIL Open Font License 1.1 (google/fonts). */',
];
let total = 0;
for (const f of FONTS) {
  const file = f.src.split('/')[1];
  const cached = join(CACHE, file);
  if (!existsSync(cached)) {
    const url = GF + f.src.replace(/\[/g, '%5B').replace(/\]/g, '%5D');
    console.log(`downloading ${url}`);
    const r = await fetch(url);
    if (!r.ok) throw new Error(`${url}: HTTP ${r.status}`);
    writeFileSync(cached, new Uint8Array(await r.arrayBuffer()));
  }
  // keep the copyright, licence and licence-URL entries of the name table (OFL)
  const buf = await subsetFont(readFileSync(cached), text, { targetFormat: 'woff2', preserveNameIds: [0, 13, 14] });
  const name = `${f.family.toLowerCase().replace(/ variable$/, '').replace(/ /g, '-')}-${f.weight.includes(' ') ? 'var' : f.weight}.woff2`;
  writeFileSync(join(OUT, name), buf);
  total += buf.length;
  console.log(`${name.padEnd(32)} ${(buf.length / 1024).toFixed(0).padStart(5)} kB`);
  css.push(`@font-face {
  font-family: '${f.family}';
  font-style: normal;
  font-weight: ${f.weight};
  font-display: swap;
  src: url(./${name}) format('woff2');
}`);
}
writeFileSync(join(OUT, 'fonts.css'), css.join('\n') + '\n');
writeFileSync(charsFile, text);
console.log(`${FONTS.length} fonts, ${chars.length} characters, ${(total / 1024).toFixed(0)} kB in total`);
